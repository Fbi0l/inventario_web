-- 3) Gravacao interna. So aceita chamadas feitas de dentro de um gatilho
--    (pg_trigger_depth() > 0); chamada direta pela API e recusada.
CREATE OR REPLACE FUNCTION public.registrar_auditoria(
  p_acao text, p_entidade text, p_entidade_id text, p_descricao text, p_detalhes jsonb
) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_uid uuid := auth.uid();
BEGIN
  IF pg_trigger_depth() = 0 THEN
    RAISE EXCEPTION 'Uso interno.';
  END IF;
  INSERT INTO public.auditoria(autor_id, autor_email, acao, entidade, entidade_id, descricao, detalhes)
  VALUES (v_uid, (SELECT u.email FROM auth.users u WHERE u.id = v_uid),
          p_acao, p_entidade, p_entidade_id, left(coalesce(p_descricao, ''), 500),
          coalesce(p_detalhes, '{}'::jsonb));
END; $$;
REVOKE ALL ON FUNCTION public.registrar_auditoria(text,text,text,text,jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.registrar_auditoria(text,text,text,text,jsonb) TO authenticated;

-- Campos alterados entre dois registros (ignora carimbos de data automaticos).
CREATE OR REPLACE FUNCTION public.auditoria_diferencas(p_antes jsonb, p_depois jsonb)
RETURNS jsonb LANGUAGE sql IMMUTABLE SET search_path = '' AS $$
  SELECT coalesce(jsonb_object_agg(c.k, jsonb_build_object('antes', p_antes -> c.k, 'depois', p_depois -> c.k)), '{}'::jsonb)
  FROM (SELECT key AS k FROM jsonb_each(coalesce(p_antes, '{}'::jsonb))
        UNION SELECT key FROM jsonb_each(coalesce(p_depois, '{}'::jsonb))) c
  WHERE c.k NOT IN ('updated_at', 'created_at')
    AND (p_antes -> c.k) IS DISTINCT FROM (p_depois -> c.k);
$$;

-- 4) Edicoes diretas em equipamentos e movimentacoes.
--    SECURITY INVOKER de proposito: current_user = 'authenticated' identifica alteracoes
--    feitas diretamente pela API. As funcoes do sistema (retirada, devolucao, arquivamento,
--    restauracao, importacao) rodam como proprietario e tem registro proprio.
CREATE OR REPLACE FUNCTION public.auditar_edicao_direta()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE v_antes jsonb; v_depois jsonb; v_ref jsonb; v_dif jsonb; v_entidade text; v_rotulo text;
BEGIN
  IF current_user <> 'authenticated' THEN RETURN NULL; END IF;
  IF TG_OP <> 'INSERT' THEN v_antes := to_jsonb(OLD); END IF;
  IF TG_OP <> 'DELETE' THEN v_depois := to_jsonb(NEW); END IF;
  v_ref := coalesce(v_depois, v_antes);
  v_dif := public.auditoria_diferencas(v_antes, v_depois);
  IF TG_OP = 'UPDATE' AND v_dif = '{}'::jsonb THEN RETURN NULL; END IF;
  IF TG_TABLE_NAME = 'equipamentos' THEN
    v_entidade := 'equipamento';
    v_rotulo := concat_ws(' — ', nullif(v_ref ->> 'tag', ''), v_ref ->> 'descricao');
  ELSE
    v_entidade := 'movimentacao';
    v_rotulo := concat_ws(' — ', v_ref ->> 'tipo', v_ref ->> 'responsavel');
  END IF;
  PERFORM public.registrar_auditoria(
    CASE TG_OP WHEN 'INSERT' THEN 'criou' WHEN 'UPDATE' THEN 'alterou' ELSE 'excluiu' END,
    v_entidade, v_ref ->> 'id', v_rotulo,
    CASE TG_OP WHEN 'UPDATE' THEN jsonb_build_object('alteracoes', v_dif)
               WHEN 'DELETE' THEN jsonb_build_object('registro', v_antes)
               ELSE jsonb_build_object('registro', v_depois) END);
  RETURN NULL;
END; $$;
DROP TRIGGER IF EXISTS trg_auditar_equipamentos ON public.equipamentos;
CREATE TRIGGER trg_auditar_equipamentos
  AFTER INSERT OR UPDATE OR DELETE ON public.equipamentos
  FOR EACH ROW EXECUTE FUNCTION public.auditar_edicao_direta();
DROP TRIGGER IF EXISTS trg_auditar_movimentacoes ON public.movimentacoes;
CREATE TRIGGER trg_auditar_movimentacoes
  AFTER INSERT OR UPDATE OR DELETE ON public.movimentacoes
  FOR EACH ROW EXECUTE FUNCTION public.auditar_edicao_direta();

-- 5) Ciclos: arquivamento, restauracao e exclusao de periodo.
CREATE OR REPLACE FUNCTION public.auditar_ciclo()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM public.registrar_auditoria('arquivou', 'ciclo', NEW.id::text, NEW.nome,
      jsonb_build_object('equipamentos', NEW.quantidade_equipamentos, 'movimentacoes', NEW.quantidade_movimentacoes));
  ELSIF TG_OP = 'UPDATE' THEN
    IF OLD.restaurado_em IS NULL AND NEW.restaurado_em IS NOT NULL THEN
      PERFORM public.registrar_auditoria('restaurou', 'ciclo', NEW.id::text, NEW.nome,
        jsonb_build_object('equipamentos', NEW.quantidade_equipamentos, 'movimentacoes', NEW.quantidade_movimentacoes));
    END IF;
  ELSE
    PERFORM public.registrar_auditoria('excluiu', 'ciclo', OLD.id::text, OLD.nome,
      jsonb_build_object('equipamentos', OLD.quantidade_equipamentos, 'movimentacoes', OLD.quantidade_movimentacoes,
                         'ja_restaurado', OLD.restaurado_em IS NOT NULL));
  END IF;
  RETURN NULL;
END; $$;
DROP TRIGGER IF EXISTS trg_auditar_ciclos ON public.ciclos_arquivados;
CREATE TRIGGER trg_auditar_ciclos
  AFTER INSERT OR UPDATE OR DELETE ON public.ciclos_arquivados
  FOR EACH ROW EXECUTE FUNCTION public.auditar_ciclo();

-- 6) Importacoes de planilha (um registro por lote confirmado).
CREATE OR REPLACE FUNCTION public.auditar_importacao()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE v_importados int := coalesce((NEW.resultado ->> 'importados')::int, 0);
        v_ignorados int := coalesce(jsonb_array_length(NEW.resultado -> 'ignorados'), 0);
BEGIN
  PERFORM public.registrar_auditoria('importou', 'planilha', NEW.lote_id::text,
    format('%s importado(s), %s ignorado(s)', v_importados, v_ignorados),
    jsonb_build_object('importados', v_importados, 'ignorados', v_ignorados));
  RETURN NULL;
END; $$;
DROP TRIGGER IF EXISTS trg_auditar_importacoes ON public.importacoes_equipamentos;
CREATE TRIGGER trg_auditar_importacoes
  AFTER INSERT ON public.importacoes_equipamentos
  FOR EACH ROW EXECUTE FUNCTION public.auditar_importacao();

